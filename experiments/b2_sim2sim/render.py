"""Render stored physical trajectories only; never run a policy or physics step."""
import os
os.environ.setdefault('MUJOCO_GL','egl')
os.environ.setdefault('MUJOCO_EGL_DEVICE_ID','6')
import argparse,json,hashlib
from pathlib import Path
import mujoco,numpy as np
import imageio.v2 as imageio
from PIL import Image,ImageDraw,ImageFont

ROOT=Path(__file__).resolve().parents[2]
FONT='/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'

def render(folder,bullet_folder):
    out=folder/'videos';out.mkdir(exist_ok=True)
    font=ImageFont.truetype(FONT,22);small=ImageFont.truetype(FONT,16)
    labels={'mujoco':'MuJoCo CPU','mjlab':'mjlab / MuJoCo Warp','bullet':'Bullet (inertia caveat)'}
    W,H=512,390;manifest=[]
    for kg in [0,5]:
        m=mujoco.MjModel.from_xml_path(str(ROOT/f'experiments/b2_sim2sim/inputs/b2_{kg}kg.xml'))
        m.vis.global_.offwidth=W;m.vis.global_.offheight=H
        m.vis.global_.fovy=50
        m.vis.headlight.ambient[:]=.45;m.vis.headlight.diffuse[:]=.5
        for g in np.flatnonzero(m.geom_type==mujoco.mjtGeom.mjGEOM_PLANE):m.geom_rgba[g]=[.72,.76,.8,1]
        opt=mujoco.MjvOption();opt.geomgroup[:]=[1,1,1,0,0,0]
        cam=mujoco.MjvCamera();cam.azimuth=130;cam.elevation=-13;cam.distance=4.3;cam.lookat[:]=[-.1,0,.85]
        d=mujoco.MjData(m)
        with mujoco.Renderer(m,height=H,width=W) as renderer:
            for case in ['reference','measured','combined']:
                entries=[]
                for b in labels:
                    base=bullet_folder if b=='bullet' else folder
                    source=base/b/f'{kg}kg_{case}'
                    r=json.loads((source/'result.json').read_text());a=dict(np.load(source/'rollout.npz'));s=dict(np.load(source/'substeps.npz'))
                    entries.append((b,r,a,s,source))
                video=out/f'B2_C1_2000_{kg}kg_{case}_3backends.mp4'
                snapshots=[]
                with imageio.get_writer(video,fps=25,codec='libx264',quality=8,macro_block_size=2) as writer:
                    for frame,i in enumerate(range(0,775,2)):
                        canvas=Image.new('RGB',(W*3,590),(18,25,35));draw=ImageDraw.Draw(canvas)
                        draw.text((14,10),f'B2 C1 iteration 2000 | {kg} kg | start/condition: {case} | t={(i+1)*.02:.2f}s',font=font,fill='white')
                        draw.text((14,42),'Frozen deployment policy | trial 0 chosen in advance | 1x speed | not hardware acceptance',font=small,fill='#afc8dd')
                        for panel,(b,r,a,s,source) in enumerate(entries):
                            d.qpos[:]=a['qpos'][i,0];mujoco.mj_forward(m,d)
                            renderer.update_scene(d,camera=cam,scene_option=opt)
                            canvas.paste(Image.fromarray(renderer.render()),(panel*W,104))
                            draw=ImageDraw.Draw(canvas);draw.text((panel*W+12,76),labels[b],font=font,fill='white')
                            k=abs(s['time_s']-a['time_s'][i]).argmin();t=r['trials'][0]
                            draw.text((panel*W+12,506),f'Speed {abs(s["dq"][k,0]).max():.2f} rad/s | power {s["power"][k,0]:.0f} W',font=small,fill='#d5e4f0')
                            draw.text((panel*W+12,531),f'Final motion: {"PASS" if t["task_pass"] else "FAIL"} | actuator: {"PASS" if t["actuator_pass"] else "FAIL"}',font=small,fill='#eeb078')
                            draw.text((panel*W+12,556),f'Peak {t["peak_speed_rad_s"]:.2f} rad/s / {t["peak_power_w"]:.0f} W',font=small,fill='#afc8dd')
                        writer.append_data(np.array(canvas))
                        if i in [0,100,200,400,650,774]:snapshots.append(canvas.copy())
                sheet=Image.new('RGB',(W*3,590*len(snapshots)))
                for j,img in enumerate(snapshots):sheet.paste(img,(0,590*j))
                sheet.save(video.with_suffix('.jpg'))
                snapshots[2].save(video.with_name(video.stem+'_preview.jpg'))
                manifest.append(dict(video=str(video),kg=kg,case=case,trial=0,frames=388,fps=25,
                  sha256=hashlib.sha256(video.read_bytes()).hexdigest(),sources=[str(e[4]) for e in entries],
                  rendered_with='MuJoCo renderer for all three; trajectories generated by named physics backends',
                  state_not_modified=True,full_acceptance=False))
                print(str(video),flush=True)
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--folder',type=Path,required=True);p.add_argument('--bullet-folder',type=Path,required=True)
    a=p.parse_args();render(a.folder,a.bullet_folder)
